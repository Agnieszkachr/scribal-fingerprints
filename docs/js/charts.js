function renderWithinClassTable(containerId) {
  const wc = (window.DATA_ARTICLE || {}).within_class || {};
  const P = '<span class="nc">p</span>';
  const pv = x => (x && typeof x.perm_p === 'number') ? (x.perm_p < 0.001 ? '< 0.001' : (x.perm_p + 1e-9).toFixed(x.perm_p < 0.01 ? 3 : 2)) : '\u2014';
  const rows = TYPES.map(t => {
    const b = (wc.B || {})[t.key] || {}, a = (wc.A || {})[t.key] || {}, al = (wc.aleph || {})[t.key] || {};
    return [`<strong>${t.label}</strong>`, (b.n || 0).toLocaleString('en-GB'),
      fmt(b.d), `${fmt(b.ci_low)}\u2013${fmt(b.ci_high)}`, pv(b),
      fmt(a.d), pv(a), fmt(al.d), pv(al)];
  });
  setHTML(containerId, table(
    ['Class', '<span class="nc">n</span> (B)', '<span class="nc">d</span> (B)', '95 % CI', P,
     '<span class="nc">d</span> (A)', P, '<span class="nc">d</span> (\u2135)', P],
    rows,
    'Cohen\u2019s d within each variant class (up to 1,000 vectors per class) under the three baselines, with the ' +
    'block-permutation p-value (2,000 permutations) and, for baseline B, the block-bootstrap 95 % interval ' +
    '(<code>supplementary_checks.py</code>). A separation counts as evidence only if it is distinguishable from its ' +
    'permutation null under all three baselines; no value within a single class meets this criterion.'));
}

