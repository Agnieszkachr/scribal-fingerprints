function renderSplitHalf(chartId, pairsId, matrixId, baselineLabel = 'B') {
  const sh = ((window.DATA_ARTICLE || {}).split_half || {})[baselineLabel];
  if (!sh) return;
  const p = sh.pairs;
  const all = p.flatMap(r => [r.odd, r.even]);
  const lo = Math.min(...all) - 0.05, hi = Math.max(...all) + 0.05;
  Plotly.newPlot(chartId, [
    { x: [lo, hi], y: [lo, hi], mode: 'lines', line: { color: '#bbb', width: 1 }, hoverinfo: 'skip', showlegend: false },
    {
      x: p.map(r => r.odd), y: p.map(r => r.even), text: p.map(r => pairLabel(r.pair)),
      mode: 'markers+text', textposition: 'top right', type: 'scatter', showlegend: false,
      marker: { color: '#111', size: 9 },
      hovertemplate: '%{text}<br>odd %{x:.3f}, even %{y:.3f}<extra></extra>',
    },
  ], {
    ...PLOTLY_LAYOUT,
    xaxis: { title: 'Profile distance, odd chapters (cosine)', range: [lo, hi] },
    yaxis: { title: 'Profile distance, even chapters', range: [lo, hi], scaleanchor: 'x' },
  }, PLOTLY_CONFIG);

  setHTML(pairsId, table(['Pair', 'Odd chapters', 'Even chapters'],
    p.map(r => [`<strong>${pairLabel(r.pair)}</strong>`, fmt(r.odd), fmt(r.even)])));

  const m = sh.matrix;
  const lab = l => { const [ms, half] = l.split('_'); return `<span class="nc">${msLabel(ms)}<sub>${half}</sub></span>`; };
  const body = m.rows.map((row, i) => [`<strong>${lab(m.labels[i])}</strong>`].concat(
    row.map((v, j) => {
      const sameWitness = i !== j && m.labels[i].split('_')[0] === m.labels[j].split('_')[0];
      return sameWitness ? `<strong>${fmt(v)}</strong>` : fmt(v);
    })));
  setHTML(matrixId, table([''].concat(m.labels.map(lab)), body,
    'Cosine distances between the odd-half and even-half profiles of every witness (attested loci, baseline ' +
    baselineLabel + '). Bold: the two halves of the same witness.'));
}

