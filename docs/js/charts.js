function renderFeaturePlot(chartId, tableId) {
  const panel = (window.DATA_STATS || {}).feature_panel;
  if (!panel) { console.error('Feature panel not loaded'); return; }
  const rows = panel.slice().reverse();
  const y = rows.map(r => r.label);
  const traces = [
    {
      x: rows.map(r => r.d), y, type: 'scatter', mode: 'markers', name: 'Cohen’s d (all N)',
      marker: { color: '#111', size: 9 },
      error_x: {
        type: 'data', symmetric: false, color: '#444', thickness: 1.6, width: 0,
        array: rows.map(r => r.ci_high - r.d), arrayminus: rows.map(r => r.d - r.ci_low),
      },
      hovertemplate: '%{y}<br>d = %{x:.3f}<extra></extra>',
    },
    {
      x: rows.map(r => r.null_mean), y, type: 'scatter', mode: 'markers', name: 'permutation null mean',
      marker: { color: '#999', symbol: 'line-ns-open', size: 16, line: { width: 2 } },
      hovertemplate: '%{y}<br>null mean = %{x:.4f}<extra></extra>',
    },
  ];
  const draws = rows.filter(r => r.draws);
  if (draws.length) {
    traces.push({
      x: draws.flatMap(r => r.draws), y: draws.flatMap(r => r.draws.map(() => r.label)),
      type: 'scatter', mode: 'markers', name: 'single random draws',
      marker: { color: '#999', size: 6 },
      hovertemplate: 'draw: d = %{x:.4f}<extra></extra>',
    });
  }
  Plotly.newPlot(chartId, traces, {
    ...PLOTLY_LAYOUT,
    margin: { t: 20, r: 30, b: 70, l: 170 },
    xaxis: { title: 'Cohen’s d (95 % block-bootstrap CI)', zeroline: true, zerolinecolor: '#bbb' },
    yaxis: { automargin: true },
    legend: { orientation: 'h', y: -0.3, x: 0.5, xanchor: 'center', font: { size: 12 } },
  }, PLOTLY_CONFIG);

  const body = panel.map(r => [
    `<strong>${r.label}</strong>`, (r.n || 0).toLocaleString(),
    fmtCI(r.d, r.ci_low, r.ci_high),
    r.draws ? `≤ 0.05 in ${r.n_draws_significant} of ${r.draws.length} draws` : fmtP(r.p),
    r.draws ? '≈ 0' : fmt(r.ari)]);
  setHTML(tableId, table(['Condition', 'N', '<span class="nc">d</span> [95 % CI]', '<span class="nc">p</span>', 'ARI'], body,
    `Random masked: mean over ${panel[3].draws ? panel[3].draws.length : 5} draws ` +
    `(d of single draws ${panel[3].draws ? Math.min(...panel[3].draws).toFixed(3) + '–' + Math.max(...panel[3].draws).toFixed(3) : ''}); ` +
    'the same number of words per field as under content masking, at random positions.'));
}

