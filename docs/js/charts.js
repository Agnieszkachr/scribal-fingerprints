/* Witness order of the article (Table 2), then the baseline witnesses */
const WITNESS_ORDER = ['P66', 'aleph', 'A', 'D', 'B'];
const TYPES = [
  { key: 'substitution_morphological', label: 'Morphological subst.', color: '#2C5F7C' },
  { key: 'substitution_lexical',       label: 'Lexical subst.',       color: '#C4963C' },
  { key: 'substitution_word_order',    label: 'Word order',           color: '#2A7F8E' },
  { key: 'addition',                   label: 'Addition',             color: '#CB4335' },
  { key: 'omission',                   label: 'Omission',             color: '#7D3C98' },
];
const BASELINE_TAGS = { 'B': 'B', 'A': 'A', 'ℵ': 'aleph' };

const msLabel = ms => (ms === 'aleph' ? 'ℵ' : ms);
const pairLabel = p => p.split('-').map(msLabel).join('–');
const fmt = (v, dec = 3) => (typeof v === 'number' && isFinite(v) ? v.toFixed(dec) : '—');
const fmtP = (p, floor) => {
  if (typeof p !== 'number') return '—';
  if (floor !== undefined && p <= floor + 1e-9) return `${p.toFixed(4)} (minimum)`;
  const s = (p + 1e-9).toFixed(3);
  return s === '0.000' ? '< 0.001' : s;
};
const fmtCI = (v, lo, hi, dec = 3) =>
  (typeof lo === 'number' && typeof hi === 'number')
    ? `${fmt(v, dec)} [${fmt(lo, dec)}–${fmt(hi, dec)}]` : fmt(v, dec);
const byOrder = (a, b) => WITNESS_ORDER.indexOf(a) - WITNESS_ORDER.indexOf(b);

function setHTML(id, html) {
  const el = document.getElementById(id);
  if (el) el.innerHTML = html;
}

function table(head, rows, note) {
  let html = '<table><thead><tr>' + head.map(h => `<th>${h}</th>`).join('') + '</tr></thead><tbody>';
  rows.forEach(r => { html += '<tr>' + r.map(c => `<td>${c}</td>`).join('') + '</tr>'; });
  html += '</tbody></table>';
  if (note) html += `<p class="table-note">${note}</p>`;
  return html;
}

/* ------------------------------------------------------------
   Finding 1 — variant typology (article § 5.1, Table 2, Figures 1–2)
   ------------------------------------------------------------ */

function typeShares(baselineLabel) {
  const all = window.DATA_TYPES_ALL || {};
  const rows = all[BASELINE_TAGS[baselineLabel]] || [];
  return rows.slice().sort((a, b) => byOrder(a.manuscript, b.manuscript)).map(r => {
    const n = r.total_variants;
    const shares = {};
    TYPES.forEach(t => { shares[t.key] = 100 * (r[t.key] || 0) / n; });
    return { ms: r.manuscript, n, shares };
  });
}

function renderTypeShares(chartId, tableId, baselineLabel) {
  const rows = typeShares(baselineLabel);
  if (!rows.length) { console.error('Type counts not loaded'); return; }
  const x = rows.map(r => `${msLabel(r.ms)}<br>n = ${r.n.toLocaleString('en-GB')}`);
  const traces = TYPES.map(t => ({
    x, y: rows.map(r => r.shares[t.key]),
    name: t.label, type: 'bar', marker: { color: t.color },
    hovertemplate: `%{x}<br>${t.label}: %{y:.1f}%<extra></extra>`,
  }));
  Plotly.newPlot(chartId, traces, {
    ...PLOTLY_LAYOUT,
    barmode: 'group',
    yaxis: { title: 'Share of the witness’s variants (%)', rangemode: 'tozero' },
    legend: { orientation: 'h', y: -0.18, x: 0.5, xanchor: 'center' },
  }, PLOTLY_CONFIG);

  const head = ['Witness', 'n'].concat(TYPES.map(t => t.label));
  const body = rows.map(r => [`<strong>${msLabel(r.ms)}</strong>`, r.n.toLocaleString()]
    .concat(TYPES.map(t => r.shares[t.key].toFixed(1))));
  setHTML(tableId, table(head, body, `Per cent of each witness’s variants against baseline ${baselineLabel}.`));
}

function renderTypologyTable(containerId) {
  const cfg = (window.DATA_STATS || {}).configs || {};
  const sbl = (window.DATA_ARTICLE || {}).sbl;
  const rows = [];
  [['B', 'Baseline B'], ['A', 'Baseline A'], ['ℵ', 'Baseline ℵ']].forEach(([lab, key]) => {
    const c = cfg[key];
    if (!c) return;
    rows.push([`<strong>${lab}</strong>`, (c.N_current || c.N || 0).toLocaleString(),
      fmtCI(c["Cramer's V Broad"], c["Cramer's V Broad_CI_Low"], c["Cramer's V Broad_CI_High"]),
      fmtP(c["Cramer's V Broad_P"]),
      fmtCI(c["Cramer's V Sub"], c["Cramer's V Sub_CI_Low"], c["Cramer's V Sub_CI_High"]),
      fmtP(c["Cramer's V Sub_P"])]);
  });
  if (sbl) {
    const b = sbl.association["Cramer's V Broad"], s = sbl.association["Cramer's V Sub"];
    rows.push(['<strong>SBL edition</strong>', sbl.n.toLocaleString(),
      fmtCI(b.v, b.ci_low, b.ci_high), fmtP(b.perm_p), fmtCI(s.v, s.ci_low, s.ci_high), fmtP(s.perm_p)]);
  }
  setHTML(containerId, table(
    ['Baseline', 'N', '<span class="nc">V</span>, broad classes [95 % CI]', '<span class="nc">p</span>', '<span class="nc">V</span>, substitution sub-classes [95 % CI]', '<span class="nc">p</span>'],
    rows,
    'Cramér’s V between witness and variant type; block-bootstrap intervals (chapters resampled), ' +
    'block-permutation p-values (labels shuffled within chapters, 200 permutations; the smallest attainable value is 0.005). ' +
    'Broad classes: substitution, addition, omission. Against the SBL edition Vaticanus is itself one of the witnesses ' +
    '(301 variants, 0.35 per attested verse).'));
}

