function renderSinaiticusTable(containerId) {
  const tc = (window.DATA_ARTICLE || {}).text_checks;
  if (!tc) return;
  const s = tc.shared_with_aleph_by_stretch;
  const anchors = [['B', 'B'], ['A', 'A'], ['SBL', 'SBL edition']];
  const rows = [];
  anchors.forEach(([key, lab]) => {
    if (!s[key]) return;
    Object.keys(s[key]).sort(byOrder).forEach(ms => {
      const r = s[key][ms];
      const a = r['1:1-8:38'], b = r['8:39-21:25'];
      rows.push([lab, `<strong>${msLabel(ms)}</strong>`,
        `${fmt(a.percent, 1)} (${a.shared}/${a.variants})`,
        `${fmt(b.percent, 1)} (${b.shared}/${b.variants})`,
        fmtP(r.fisher_p)]);
    });
  });
  setHTML(containerId, table(
    ['Baseline', 'Witness', 'Shared with ℵ, 1:1–8:38 (%)', 'Shared with ℵ, 8:39–21:25 (%)', 'Fisher <span class="nc">p</span>'],
    rows,
    'Share of a witness’s variants that are also variants of Sinaiticus (same verse, same baseline reading, same witness reading). ' +
    'The fall after 8:38 in the agreement of Bezae with Sinaiticus holds under every baseline (Fee 1968).'));
}

