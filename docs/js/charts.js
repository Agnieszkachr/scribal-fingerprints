function renderStabilityHeatmap(containerId) {
  const data = window.DATA_STABILITY;
  if (!data) { console.error('Stability data not loaded'); return; }
  const manuscripts = Object.keys(data).sort(byOrder);
  const allChapters = [...new Set(manuscripts.flatMap(ms => data[ms].map(d => d.chapter)))].sort((a, b) => a - b);
  const z = manuscripts.map(ms => allChapters.map(ch => {
    const entry = data[ms].find(d => d.chapter === ch);
    return entry ? entry.distance : null;
  }));
  Plotly.newPlot(containerId, [{
    z, x: allChapters.map(String), y: manuscripts.map(msLabel), type: 'heatmap',
    colorscale: [[0, '#FFF8E1'], [0.3, '#FFE082'], [0.5, '#FFA726'], [0.7, '#E65100'], [1, '#B71C1C']],
    hovertemplate: '%{y} ch.%{x}: %{z:.3f}<extra></extra>',
    colorbar: { title: 'Cosine distance', titleside: 'right', thickness: 15, len: 0.8 },
  }], {
    ...PLOTLY_LAYOUT,
    xaxis: { title: 'Chapter', type: 'category' },
    yaxis: { title: '' },
    margin: { ...PLOTLY_LAYOUT.margin, l: 60 },
  }, PLOTLY_CONFIG);
}
